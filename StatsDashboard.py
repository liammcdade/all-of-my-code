    def on_simulation_complete(self, output, error):
        """Called on main thread after simulation finishes."""
        self.run_btn.config(state=tk.NORMAL)

        if error:
            self.status_label.config(text="❌ Error", foreground="red")
            self.raw_text.insert(tk.END, f"ERROR: {error}\n")
            messagebox.showerror("Simulation Error", error)
            return

        self.status_label.config(text="✅ Complete", foreground="green")
        self.raw_text.delete("1.0", tk.END)
        self.raw_text.insert(tk.END, output)

        # Parse the table from output
        rows = self._parse_table(output)
        if rows:
            self._populate_table(rows)
            self.notebook.select(0)  # Switch to table tab
        else:
            self.status_label.config(text="⚠️ Done but couldn't parse table", foreground="orange")
            self.notebook.select(1)  # Switch to raw output tab

    def _parse_table(self, output: str) -> list[dict]:
        """
        Parse league table rows from raw simulation output.
        Handles both PL and NLN formats by looking for numeric patterns.
        """
        rows = []
        lines = output.strip().split("\n")
        in_table = False

        for line in lines:
            stripped = line.strip()
            # Detect table header or separator lines
            if stripped.startswith("---") or stripped.startswith("==="):
                continue
            if "Pos" in stripped and "Team" in stripped and "Pts" in stripped:
                in_table = True
                continue
            if not in_table:
                continue
            if not stripped or stripped.startswith("="):
                if rows:  # End of table block
                    break
                continue

            # Try to parse a data row
            parts = stripped.split()
            if len(parts) < 8:
                continue

            try:
                pos = int(parts[0])
                # Find where numeric stats start after team name
                # Team name can be multi-word; scan from right for known stat count
                # Expected: P W D L GF GA GD Pts [ELO] [Status...]
                # Work backwards from end to find stats
                numeric_parts = []
                idx = len(parts) - 1
                while idx > 0:
                    try:
                        float(parts[idx].replace("+", "").replace("-", ""))
                        numeric_parts.insert(0, parts[idx])
                        idx -= 1
                    except ValueError:
                        break

                if len(numeric_parts) >= 8:
                    team_name = " ".join(parts[1:idx + 1])
                    p = int(numeric_parts[0])
                    w = int(numeric_parts[1])
                    d = int(numeric_parts[2])
                    l = int(numeric_parts[3])
                    gf = int(numeric_parts[4])
                    ga = int(numeric_parts[5])
                    gd_str = numeric_parts[6]
                    gd = int(gd_str.replace("+", ""))
                    pts = int(numeric_parts[7])
                    elo = float(numeric_parts[8]) if len(numeric_parts) > 8 else 0.0

                    # Check for status text at end
                    status = ""
                    remaining = parts[idx + 1 + len(numeric_parts):]
                    if remaining:
                        status = " ".join(remaining)

                    rows.append({
                        "pos": pos, "team": team_name, "p": p, "w": w, "d": d,
                        "l": l, "gf": gf, "ga": ga, "gd": gd, "pts": pts,
                        "elo": round(elo, 1), "status": status.upper()
                    })
            except (ValueError, IndexError):
                continue

        return sorted(rows, key=lambda r: (-r["pts"], -r["gd"], -r["gf"]))

    def _populate_table(self, rows: list[dict]):
        for item in self.tree.get_children():
            self.tree.delete(item)

        n_teams = len(rows)
        for row in rows:
            tag = self._get_row_tag(row, n_teams)
            gd_display = f"+{row['gd']}" if row['gd'] > 0 else str(row['gd'])
            values = (
                row["pos"], row["team"], row["p"], row["w"], row["d"],
                row["l"], row["gf"], row["ga"], gd_display, row["pts"], row["elo"]
            )
            self.tree.insert("", tk.END, values=values, tags=(tag,))

    def _get_row_tag(self, row: dict, n_teams: int) -> str:
        """Determine color tag based on position/status."""
        status = row.get("status", "")
        pos = row["pos"]

        if "CHAMPION" in status or "PROMOTED" in status:
            return "champion"
        if "PLAYOFF" in status:
            return "playoff"
        if "RELEGAT" in status:
            return "relegated"

        # Fallback positional coloring
        if n_teams == 20:  # Premier League
            if pos == 1:
                return "champion"
            if pos <= 4:
                return "ucl"
            if pos == 5:
                return "europa"
            if pos >= 18:
                return "relegated"
        elif n_teams == 24:  # National League
            if pos == 1:
                return "champion"
            if 2 <= pos <= 7:
                return "playoff"
            if pos >= 21:
                return "relegated"

        return "safe"


