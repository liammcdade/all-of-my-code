class SimulationWorker(threading.Thread):
    """Runs the simulation in a background thread and captures stdout."""

    def __init__(self, league_key, callback):
        super().__init__(daemon=True)
        self.league_key = league_key
        self.callback = callback
        self.output = ""
        self.error = None

    def run(self):
        try:
            dir_path, filename = LEAGUE_CONFIGS[self.league_key]
            module_name = filename.replace(".py", "")

            # Add directory to path temporarily for import
            if dir_path not in sys.path:
                sys.path.insert(0, dir_path)

            # Capture stdout generated by print() statements in the sim
            f = io.StringIO()
            with redirect_stdout(f):
                # Import and execute main()
                # We use importlib to handle hyphens in filenames like '26-27-season'
                import importlib.util
                spec = importlib.util.spec_from_file_location(module_name, os.path.join(dir_path, filename))
                mod = importlib.util.module_from_spec(spec)
                
                # Prevent the script's `if __name__ == "__main__"` guard from blocking
                # by directly calling main() after loading
                spec.loader.exec_module(mod)
                
                if hasattr(mod, "main"):
                    mod.main()
                else:
                    raise AttributeError(f"No main() function found in {filename}")

            self.output = f.getvalue()

        except Exception as e:
            self.error = str(e)
        finally:
            # Clean up sys.path
            if dir_path in sys.path:
                sys.path.remove(dir_path)

        # Schedule UI update on main thread
        self.callback(self.output, self.error)


